import { ChatInputCommandInteraction, SlashCommandBuilder } from 'discord.js';

export const rulesCommand = {
  data: new SlashCommandBuilder()
    .setName('rules')
    .setDescription('הצג את חוקי השימוש והרישום של תתי-דומיינים.'),
  async execute(interaction: ChatInputCommandInteraction) {
    await interaction.reply({
      content: `⚖️ **תנאי השימוש וכללי רישום תת-דומיין - מפתח.ישראל:**

על מנת לשמור על איכות השירות והביטחון של קהילת המפתחים, כל בקשת רישום כפופה לכללים הבאים:

1️⃣ **תוכן חוקי בלבד**
חל איסור מוחלט על הפניית תתי-דומיינים לאתרים המכילים תוכן לא חוקי, הימורים, הפרת זכויות יוצרים, פישינג או תכנים פוגעניים.

2️⃣ **פרויקטים פעילים**
תת-דומיין שיישאר לא פעיל (ללא הפניה תקינה או ללא תעבורה/אתר פעיל) במשך תקופה ממושכת עשוי להימחק, וזאת כדי לאפשר לאחרים להשתמש בשם זה.

3️⃣ **ללא שימוש לרעה (Abuse)**
אין להשתמש בתתי-הדומיינים למטרות ספאם, מתקפות מניעת שירות (DDoS) או פעילויות זדוניות אחרות.

4️⃣ **שינוי ועדכון פרטים**
במידה ותרצו לעדכן את רשומת ה-DNS שלכם (למשל שינוי כתובת IP), תוכלו לעשות זאת ישירות דרך האתר או על ידי פנייה למנהלים בדיסקורד.

*הפרת אחד או יותר מהכללים הללו תוביל לביטול תת-הדומיין באופן מיידי וללא התראה מוקדמת.*`,
      ephemeral: true,
    });
  },
};
